import AppKit
import Vision

/// Watches the system pasteboard, records changes into the history, and writes entries back.
final class PasteboardMonitor {
    private let store: HistoryStore
    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?

    /// Called for locally copied text that should be synced to paired devices.
    var onLocalText: ((String) -> Void)?

    private static let maxTextBytes = 5 * 1024 * 1024
    private static let maxRichBytes = 512 * 1024

    /// Markers password managers and other apps set on content that must not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    private static let ignoredApps: Set<String> = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "org.keepassxc.keepassxc",
        "com.dashlane.dashlanephonefinal",
    ]

    init(store: HistoryStore) {
        self.store = store
        lastChange = pb.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func check() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        capture()
    }

    private func capture() {
        let types = pb.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let bundle = app?.bundleIdentifier, Self.ignoredApps.contains(bundle) { return }

        func stamp(_ item: ClipItem) -> ClipItem {
            var item = item
            item.sourceApp = app?.localizedName
            item.sourceBundleID = app?.bundleIdentifier
            return item
        }

        let urls = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            store.add(stamp(ClipItem(kind: .file, text: paths, hash: sha256Hex(Data(("f:" + paths).utf8)))))
            return
        }

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= Self.maxTextBytes else { return }
            var item = ClipItem(kind: Classifier.kind(for: text), text: text, hash: Self.textHash(text))
            if let rtf = pb.data(forType: .rtf), rtf.count <= Self.maxRichBytes { item.rtf = rtf }
            if let html = pb.data(forType: .html), html.count <= Self.maxRichBytes { item.html = html }
            store.add(stamp(item))
            onLocalText?(text)
            return
        }

        if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: raw),
           let png = rep.representation(using: .png, properties: [:]) {
            let hash = sha256Hex(png)
            if let existing = store.item(withHash: hash) {
                store.touch(existing.id)
                return
            }
            guard let name = store.saveImage(png, hash: hash) else { return }
            var item = ClipItem(kind: .image, text: "", hash: hash)
            item.imageFile = name
            item.imageWidth = rep.pixelsWide
            item.imageHeight = rep.pixelsHigh
            let saved = store.add(stamp(item))
            recognizeText(in: png) { [weak store] text in
                if !text.isEmpty { store?.setOCR(saved.id, text: text) }
            }
        }
    }

    static func textHash(_ text: String) -> String { sha256Hex(Data(("t:" + text).utf8)) }

    var currentText: String? { pb.string(forType: .string) }

    /// Puts a history entry back on the pasteboard without recording it as a new copy.
    func write(_ item: ClipItem, plainOnly: Bool = false) {
        pb.clearContents()
        switch item.kind {
        case .image:
            if let data = store.imageData(for: item) {
                pb.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .file:
            pb.writeObjects(item.filePaths.map { URL(fileURLWithPath: $0) as NSURL })
        default:
            pb.setString(item.text, forType: .string)
            if !plainOnly {
                if let rtf = item.rtf { pb.setData(rtf, forType: .rtf) }
                if let html = item.html { pb.setData(html, forType: .html) }
            }
        }
        lastChange = pb.changeCount
    }

    /// Sets clipboard text received from a paired device; it is not echoed back.
    func writeRemote(_ text: String) {
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount
    }

    /// Simulates ⌘V in the frontmost app. Requires Accessibility permission.
    static func sendPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgAnnotatedSessionEventTap)
        up?.post(tap: .cgAnnotatedSessionEventTap)
    }
}

/// On-device OCR so copied images are searchable by their text.
private func recognizeText(in image: Data, completion: @escaping (String) -> Void) {
    DispatchQueue.global(qos: .utility).async {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.automaticallyDetectsLanguage = true
        try? VNImageRequestHandler(data: image).perform([request])
        let text = (request.results ?? [])
            .compactMap { $0.topCandidates(1).first?.string }
            .joined(separator: "\n")
        DispatchQueue.main.async { completion(text) }
    }
}
